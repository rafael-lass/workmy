from typing import Protocol
from contextlib import AbstractAsyncContextManager
from pathlib import Path
from src.application.dto.excel_export import ExportPeriod


class IExcelExportQuery(Protocol):
    def snapshot(self) -> AbstractAsyncContextManager: ...
    async def payments(self, user_id: int, period: ExportPeriod) -> list[dict]: ...
    async def projects(self, user_id: int, period: ExportPeriod) -> list[dict]: ...
    async def clients(self, user_id: int, period: ExportPeriod) -> list[dict]: ...
    async def services(self, user_id: int, period: ExportPeriod) -> list[dict]: ...


class IExcelRenderer(Protocol):
    def render(self, data: dict, period: ExportPeriod, mode: str = 'parallel') -> tuple[Path, dict[str, float], dict[str, int]]: ...
